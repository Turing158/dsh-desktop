//! The window and taskbar icon: the DSH mark, in one of two inks.
//!
//! The icon follows the **Windows** theme, not the app's own appearance
//! setting. That is the one place in this app where the two deliberately
//! disagree: the frame (`titlebar.rs`) follows the DSH preference, because it
//! sits directly above the app's own sidebar and would band against it
//! otherwise, while the taskbar is a Windows surface among other Windows
//! surfaces and has to follow the theme *it* is drawn in. A white whale on a
//! light taskbar is invisible regardless of what the app is doing.
//!
//! ## Why the artwork is the bare mark, in two inks
//!
//! `icons/icon.ico` is the same whale in brand blue, baked into the executable
//! by `tauri-build` for the Start menu, Explorer and the installer. That one is
//! a static file: it has no theme to follow, so it keeps the app's accent colour
//! and stays legible on a light folder and a dark taskbar alike.
//!
//! This module is the *running window's* icon, which Windows does choose at
//! runtime, so it can and must follow the theme. Two reasons it is monochrome
//! rather than the blue artwork:
//!
//!   - **The bar already says "deepseek".** A taskbar button that repeats the
//!     product name next to the window's own caption is noise.
//!   - **A coloured icon cannot follow the theme.** Recolouring the brand blue
//!     per theme would mean a second brand palette. The bare mark recolours to a
//!     single flat ink for free, which is exactly what a monochrome icon set
//!     wants.
//!
//! So the taskbar shows the same mark the title bar draws, in the ink that
//! reads against the current taskbar.
//!
//! ## Where the pixels come from
//!
//! `icons/mark-black.png` and `icons/mark-white.png` are generated by
//! `tools/make-icons.mjs` from the title bar's own `LOGO_PATH`, so all four
//! icon outputs — these two, the blue `icon.ico`, and the bar's inline `<svg>` —
//! can never drift into being different artwork. They are embedded in the binary
//! with `include_bytes!` rather than read at runtime: they are ~3 KB each, and
//! a missing resource file would otherwise mean a silently icon-less window.
//!
//! Windows scales the PNG itself. Rather than committing a ladder of sizes,
//! `CreateIconFromResourceEx` is handed the metric size the window actually
//! wants (16px on a standard-DPI taskbar, 20 or 24 on a scaled one) and does
//! the resampling, which is also how a real `.ico` is consumed.

/// Which of the two marks to draw.
///
/// Named for the ink rather than for the theme that selects it: the ink is what
/// the icon *is*, and the mapping from theme to ink is one line that can be
/// read separately.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Ink {
    /// Near-black mark, for a light taskbar.
    Black,
    /// Near-white mark, for a dark taskbar.
    White,
}

/// The registry value holding the **Windows** (not app) light/dark mode.
///
/// This is the setting that decides the taskbar's colour, and it is *not* the
/// one the window's own `theme()` reports. Windows keeps two:
///
/// | Value | Controls | Read by |
/// |---|---|---|
/// | `AppsUseLightTheme` | app windows, including this one | `window.theme()` |
/// | `SystemUsesLightTheme` | taskbar, Start, Action Center | this module |
///
/// They are separate switches in Settings, and they disagree often — a light
/// taskbar with dark apps is a common configuration. Keying the icon off the
/// app theme would paint a white mark on a white taskbar for exactly that user,
/// which is the failure these two constants exist to avoid. They are written as
/// `&str` and widened at the call site so there is exactly one copy of each
/// name; `w!` needs a literal, and a second literal is how the two would drift.
#[cfg(windows)]
const SYSTEM_USES_LIGHT_THEME_KEY: &str =
    r"Software\Microsoft\Windows\CurrentVersion\Themes\Personalize";

/// The value name under [`SYSTEM_USES_LIGHT_THEME_KEY`].
#[cfg(windows)]
const SYSTEM_USES_LIGHT_THEME_VALUE: &str = "SystemUsesLightTheme";

impl Ink {
    /// The ink that reads against a taskbar of the given darkness.
    ///
    /// Deliberately total: any input maps to one of the two marks, so there is
    /// no "unknown theme" state that could leave the window with no icon.
    pub const fn for_taskbar(dark: bool) -> Self {
        if dark {
            Ink::White
        } else {
            Ink::Black
        }
    }

    /// The embedded PNG for this ink.
    pub const fn png(self) -> &'static [u8] {
        match self {
            Ink::Black => include_bytes!("../icons/mark-black.png"),
            Ink::White => include_bytes!("../icons/mark-white.png"),
        }
    }
}

/// Whether the Windows taskbar is currently dark, from `SystemUsesLightTheme`.
///
/// `None` when the value is missing or unreadable — a fresh profile, a policy
/// that removed it, or a future Windows that renamed it. The caller decides
/// what to do about not knowing.
#[cfg(windows)]
pub fn taskbar_is_dark() -> Option<bool> {
    platform::read_system_uses_light_theme().map(|light| !light)
}

/// Read `SystemUsesLightTheme`, as a light/dark answer.
///
/// # Returns
/// `Some(true)` when Windows is set to light, `Some(false)` when dark, and
/// `None` when the value cannot be read.
#[cfg(windows)]
mod platform {
    use std::sync::Mutex;

    use windows::core::PCWSTR;
    use windows::Win32::Foundation::{ERROR_SUCCESS, HWND, LPARAM, WPARAM};
    use windows::Win32::System::Registry::{
        RegGetValueW, HKEY_CURRENT_USER, RRF_RT_REG_DWORD,
    };
    use windows::Win32::UI::WindowsAndMessaging::{
        CreateIconFromResourceEx, GetSystemMetrics, SendMessageW, ICON_BIG, ICON_SMALL,
        LR_DEFAULTCOLOR, SM_CXICON, SM_CXSMICON, SM_CYICON, SM_CYSMICON, WM_SETICON,
    };

    use super::Ink;

    /// Read `SystemUsesLightTheme` from the current user's hive.
    ///
    /// Read on every call rather than cached: it costs one registry read, it
    /// happens only on startup and on a theme-change event, and a cache would
    /// need invalidating on exactly the event that already tells us to re-read.
    pub fn read_system_uses_light_theme() -> Option<bool> {
        use super::{SYSTEM_USES_LIGHT_THEME_KEY, SYSTEM_USES_LIGHT_THEME_VALUE};

        let key = wide(SYSTEM_USES_LIGHT_THEME_KEY);
        let name = wide(SYSTEM_USES_LIGHT_THEME_VALUE);

        let mut data: u32 = 0;
        let mut size = std::mem::size_of::<u32>() as u32;
        // SAFETY: `data` and `size` are correctly sized for a DWORD, which is
        // what `RRF_RT_REG_DWORD` restricts the read to, and both wide strings
        // are NUL-terminated and outlive the call.
        let status = unsafe {
            RegGetValueW(
                HKEY_CURRENT_USER,
                PCWSTR(key.as_ptr()),
                PCWSTR(name.as_ptr()),
                RRF_RT_REG_DWORD,
                None,
                Some(std::ptr::addr_of_mut!(data).cast()),
                Some(std::ptr::addr_of_mut!(size)),
            )
        };
        if status == ERROR_SUCCESS {
            Some(data != 0)
        } else {
            None
        }
    }

    /// A NUL-terminated UTF-16 copy of `text`, for a Win32 wide-string argument.
    fn wide(text: &str) -> Vec<u16> {
        text.encode_utf16().chain(std::iter::once(0)).collect()
    }

    /// One `(ICON_*, HICON)` pair, held as a raw handle value.
    ///
    /// The handle is kept as an `isize` rather than as the `HICON` newtype
    /// because it has to live in a `static`: `HICON` wraps a raw pointer and so
    /// is neither `Send` nor `Sync`, while these are never dereferenced — they
    /// are only handed back to `SendMessageW`, which is what keeps the window
    /// painting them.
    type Handle = (u32, isize);

    /// Icon handles built so far, keyed by the ink they were drawn with.
    ///
    /// A cache, not a leak. There are exactly two inks, so at most four icons
    /// (two sizes each) are ever created for the process's whole life, and
    /// switching the Windows theme back and forth rebuilds nothing.
    ///
    /// They are never destroyed, and that is deliberate rather than an
    /// oversight: the window references a handle for as long as it lives, and
    /// `WM_SETICON` gives no notification when a handle stops being used, so
    /// there is no point at which freeing one is provably safe. Windows
    /// reclaims them when the process exits.
    static BUILT: Mutex<Vec<(Ink, Vec<Handle>)>> = Mutex::new(Vec::new());

    /// Read a system metric, falling back when Windows reports nothing.
    ///
    /// `GetSystemMetrics` returns 0 for a metric it does not know, and an icon
    /// requested at 0×0 is not created at all — so a zero has to become a real
    /// size rather than being passed through.
    fn metric(
        index: windows::Win32::UI::WindowsAndMessaging::SYSTEM_METRICS_INDEX,
        fallback: i32,
    ) -> i32 {
        // SAFETY: `GetSystemMetrics` takes an index by value and reads nothing
        // from the caller.
        let value = unsafe { GetSystemMetrics(index) };
        if value > 0 {
            value
        } else {
            fallback
        }
    }

    /// Create one `HICON` from the PNG bytes at a requested pixel size.
    ///
    /// `dwVer` is `0x00030000`: the PNG payload is a version-3 icon resource,
    /// which is what makes Windows accept a PNG here at all instead of
    /// expecting a `BITMAPINFOHEADER`.
    ///
    /// # Safety
    /// Calls Win32 directly; safe to call from any thread.
    unsafe fn make_icon(png: &[u8], width: i32, height: i32) -> Option<isize> {
        // SAFETY: `png` is a `'static` slice of a valid PNG, and the call only
        // reads it.
        let icon = unsafe {
            CreateIconFromResourceEx(png, true, 0x0003_0000, width, height, LR_DEFAULTCOLOR)
        }
        .ok()?;
        Some(icon.0 as isize)
    }

    /// Build the icon for one ink, or the cache entry if it already exists.
    ///
    /// # Safety
    /// Calls Win32 directly; safe to call from any thread.
    unsafe fn icons_for(ink: Ink) -> Vec<Handle> {
        // A poisoned lock cannot leave this data inconsistent — the vector is
        // only ever pushed to — so the guard is recovered rather than panicked
        // on. Losing the icon because an unrelated thread panicked would be a
        // poor trade.
        let mut cache = BUILT.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
        if let Some((_, handles)) = cache.iter().find(|(cached, _)| *cached == ink) {
            return handles.clone();
        }

        let small = metric(SM_CXSMICON, 16);
        let small_height = metric(SM_CYSMICON, 16);
        let large = metric(SM_CXICON, 32);
        let large_height = metric(SM_CYICON, 32);

        let mut handles = Vec::new();
        // ICON_BIG is what the taskbar and Alt+Tab read; ICON_SMALL is the
        // title-bar and window-menu size. Both are set, so the window does not
        // fall back to the executable's own icon for either.
        for (kind, width, height) in [
            (ICON_BIG, large, large_height),
            (ICON_SMALL, small, small_height),
        ] {
            // SAFETY: the bytes come from `include_bytes!` and are valid for the
            // process's lifetime.
            if let Some(handle) = unsafe { make_icon(ink.png(), width, height) } {
                handles.push((kind, handle));
            }
        }

        cache.push((ink, handles.clone()));
        handles
    }

    /// Attach the window and taskbar icon for an ink.
    ///
    /// Safe to call repeatedly: an unchanged ink re-sends handles the window
    /// already has, which is idempotent and cheap.
    ///
    /// # Safety
    /// `hwnd` must be a live window handle owned by this process.
    pub unsafe fn apply(hwnd: HWND, ink: Ink) {
        // SAFETY: the caller guarantees the window is live.
        for (kind, handle) in unsafe { icons_for(ink) } {
            // SAFETY: `handle` is an `HICON` this module created and has not
            // freed, and `WM_SETICON` only stores it.
            unsafe {
                SendMessageW(
                    hwnd,
                    WM_SETICON,
                    Some(WPARAM(kind as usize)),
                    Some(LPARAM(handle)),
                );
            }
        }
    }

    /// The pixel size the taskbar would ask for, for the diagnostic log.
    pub fn taskbar_metric() -> i32 {
        metric(SM_CXICON, 32)
    }

    /// The colour of the pixel the taskbar actually paints behind the icon is
    /// not readable, so for the log the raw registry answer is the useful bit.
    pub fn describe_system_uses_light_theme() -> String {
        match read_system_uses_light_theme() {
            Some(true) => "light".to_string(),
            Some(false) => "dark".to_string(),
            None => "unreadable".to_string(),
        }
    }

    /// Create a hidden top-level window, for the icon round-trip test.
    ///
    /// A real HWND rather than a mock: `WM_SETICON`/`WM_GETICON` are only
    /// meaningful against a window that actually owns icon slots, and the whole
    /// question is whether Windows accepts these handles.
    ///
    /// # Safety
    /// Returns a live window handle the caller owns and must destroy.
    #[cfg(test)]
    pub unsafe fn create_probe_window() -> Option<HWND> {
        use windows::core::w;
        use windows::Win32::UI::WindowsAndMessaging::{
            CreateWindowExW, WINDOW_EX_STYLE, WINDOW_STYLE,
        };

        // SAFETY: the class name is a well-known system class, every optional
        // parameter is null, and the style is 0 (never shown).
        unsafe {
            CreateWindowExW(
                WINDOW_EX_STYLE(0),
                w!("STATIC"),
                w!("dsh-icon-probe"),
                WINDOW_STYLE(0),
                0,
                0,
                100,
                100,
                None,
                None,
                None,
                None,
            )
        }
        .ok()
    }
}

/// Apply the window and taskbar icon for the current **Windows** theme.
///
/// Reads `SystemUsesLightTheme` directly rather than using the window's own
/// theme, because those are two different Windows settings and the taskbar
/// follows the one the window does *not* report — see
/// [`SYSTEM_USES_LIGHT_THEME_KEY`].
///
/// A no-op on non-Windows targets so the module still compiles elsewhere.
#[cfg(windows)]
pub fn apply_to_window(window: &tauri::WebviewWindow) {
    let Ok(hwnd) = window.hwnd() else {
        return;
    };
    let hwnd = windows::Win32::Foundation::HWND(hwnd.0);

    // When the value cannot be read, fall back to the window's own theme: it is
    // at least a real signal about this machine, and it is right whenever the
    // user has not deliberately split the two settings — which is most of them.
    let dark = taskbar_is_dark().unwrap_or_else(|| {
        window
            .theme()
            .map(|theme| theme == tauri::Theme::Dark)
            .unwrap_or(false)
    });

    // SAFETY: the handle comes from the live window we were handed.
    unsafe { platform::apply(hwnd, Ink::for_taskbar(dark)) };
}

#[cfg(not(windows))]
pub fn apply_to_window(_window: &tauri::WebviewWindow) {}

/// The pixel width the taskbar asks for, for the diagnostic log.
#[cfg(windows)]
pub fn taskbar_metric() -> i32 {
    platform::taskbar_metric()
}

#[cfg(not(windows))]
pub fn taskbar_metric() -> i32 {
    0
}

/// `light`, `dark`, or `unreadable` — for the diagnostic log.
#[cfg(windows)]
pub fn describe_taskbar_theme() -> String {
    platform::describe_system_uses_light_theme()
}

#[cfg(not(windows))]
pub fn describe_taskbar_theme() -> String {
    "n/a".to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_dark_taskbar_gets_the_white_mark() {
        // The mapping the whole module exists for. Inverted, this produces a
        // black whale on a dark taskbar — present, and invisible.
        assert_eq!(Ink::for_taskbar(true), Ink::White);
        assert_eq!(Ink::for_taskbar(false), Ink::Black);
    }

    /// Read the width, height, and colour type out of a PNG's `IHDR`.
    ///
    /// Inlined rather than pulled from an image crate: the tests only need the
    /// header, and this keeps `app_icon`'s dependency list empty.
    fn ihdr(png: &[u8]) -> (u32, u32, u8) {
        assert_eq!(
            &png[..8],
            &[0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A],
            "not a PNG"
        );
        assert_eq!(&png[12..16], b"IHDR", "first chunk should be IHDR");
        let read = |at: usize| u32::from_be_bytes([png[at], png[at + 1], png[at + 2], png[at + 3]]);
        (read(16), read(20), png[25])
    }

    #[test]
    fn both_marks_are_embedded_as_square_rgba_pngs() {
        // Guards the `include_bytes!` paths and the generator's output shape.
        // A silently empty or truncated file would otherwise surface as a
        // window with no icon at all.
        for ink in [Ink::Black, Ink::White] {
            let png = ink.png();
            let (width, height, colour_type) = ihdr(png);
            assert_eq!(width, 256, "unexpected width for {ink:?}");
            assert_eq!(height, width, "{ink:?} must be square, or Windows scales it unevenly");
            assert_eq!(colour_type, 6, "{ink:?} must be RGBA (type 6), or transparency is lost");
            assert!(png.len() > 1024, "{ink:?} looks truncated: {} bytes", png.len());
        }
    }

    #[test]
    fn the_two_marks_differ_only_in_their_bytes() {
        // They must not be the same file: identical bytes would mean one of the
        // two inks renders as the other, which is invisible-on-invisible for
        // half of all Windows themes.
        assert_ne!(Ink::Black.png(), Ink::White.png());
    }

    /// The registry read must agree with the setting it claims to report.
    ///
    /// This cannot assert *which* answer is right — that is whatever the user
    /// has chosen — so it asserts the read is not silently failing. A missing
    /// value would send every user down the fallback path, which is correct but
    /// only by accident, and would hide a typo in the key path.
    #[cfg(windows)]
    #[test]
    fn the_taskbar_theme_is_readable_from_the_registry() {
        let light = platform::read_system_uses_light_theme();
        assert!(
            light.is_some(),
            "SystemUsesLightTheme could not be read; the key path or value name is wrong, \
             so the icon would always fall back to the window theme"
        );
    }

    /// `SystemUsesLightTheme` must not be confused with `AppsUseLightTheme`.
    ///
    /// These are two different values under one key, and using the wrong one is
    /// the specific bug this module was written around: they disagree whenever
    /// the user has split the two settings, which is a supported configuration.
    /// The constants are checked here so a "tidy-up" that unifies them fails
    /// loudly instead of producing a white mark on a white taskbar.
    #[test]
    #[cfg(windows)]
    fn the_taskbar_value_is_not_the_app_theme_value() {
        assert_ne!(SYSTEM_USES_LIGHT_THEME_VALUE, "AppsUseLightTheme");
        assert_eq!(SYSTEM_USES_LIGHT_THEME_VALUE, "SystemUsesLightTheme");
        assert!(
            SYSTEM_USES_LIGHT_THEME_KEY.ends_with(r"Themes\Personalize"),
            "unexpected key: {SYSTEM_USES_LIGHT_THEME_KEY}"
        );
    }

    /// The end-to-end path, against a real window.
    ///
    /// The header checks above prove the artwork is well-formed; this proves
    /// `platform::apply` actually works — that Windows accepts the PNG payload
    /// at the metric sizes this machine asks for, and that the handles stick to
    /// the window the taskbar reads them from. Both halves matter: a PNG that
    /// Windows refuses would leave the window with no icon at all rather than a
    /// wrong one, which no amount of header inspection would catch.
    #[cfg(windows)]
    #[test]
    fn both_inks_attach_to_a_real_window() {
        use windows::Win32::Foundation::LPARAM;
        use windows::Win32::UI::WindowsAndMessaging::{
            DestroyWindow, GetSystemMetrics, SendMessageW, ICON_BIG, ICON_SMALL, SM_CXICON,
            SM_CXSMICON, WM_GETICON,
        };

        // SAFETY: a message-only-ish `STATIC` window is created, exercised, and
        // destroyed within this test; nothing else holds the handle.
        unsafe {
            let hwnd = platform::create_probe_window().expect("create a probe window");

            // What this machine's taskbar and title bar actually ask for.
            let big = GetSystemMetrics(SM_CXICON);
            let small = GetSystemMetrics(SM_CXSMICON);
            assert!(big > 0 && small > 0, "unexpected metrics: {big}x{small}");

            for ink in [Ink::Black, Ink::White] {
                platform::apply(hwnd, ink);

                for kind in [ICON_BIG, ICON_SMALL] {
                    let read = SendMessageW(
                        hwnd,
                        WM_GETICON,
                        Some(windows::Win32::Foundation::WPARAM(kind as usize)),
                        Some(LPARAM(0)),
                    );
                    assert_ne!(
                        read.0, 0,
                        "{ink:?} did not stick for {} — the taskbar would fall back to \
                         the executable's icon",
                        if kind == ICON_BIG { "ICON_BIG" } else { "ICON_SMALL" }
                    );
                }
            }

            // The two inks must be distinguishable windows-side too, or the
            // theme switch would re-send the same icon and change nothing.
            platform::apply(hwnd, Ink::Black);
            let black = SendMessageW(hwnd, WM_GETICON, Some(windows::Win32::Foundation::WPARAM(ICON_BIG as usize)), Some(LPARAM(0)));
            platform::apply(hwnd, Ink::White);
            let white = SendMessageW(hwnd, WM_GETICON, Some(windows::Win32::Foundation::WPARAM(ICON_BIG as usize)), Some(LPARAM(0)));
            assert_ne!(black.0, white.0, "both inks produced the same handle");

            DestroyWindow(hwnd).expect("destroy the probe window");
        }
    }
}

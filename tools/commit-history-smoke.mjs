import assert from 'node:assert/strict'
import { join } from 'node:path'
import { writeFile } from 'node:fs/promises'
import { git } from '../dsh-plugin/sidebar-changes/host/git-provider.mjs'

export async function checkCommitHistory({ page, workspace, root, sessionId, report, chooseSource }) {
  const tree = (await git(workspace, ['rev-parse', 'HEAD^{tree}'])).toString().trim()
  const branch = (await git(workspace, ['symbolic-ref', 'HEAD'])).toString().trim()
  const commit = async (parents, text, options = []) => (await git(workspace, [...options, 'commit-tree', tree, ...parents.flatMap(id => ['-p', id])], undefined, text)).toString().trim()
  const ids = [(await git(workspace, ['rev-parse', 'HEAD'])).toString().trim()]
  for (let i = 0; i < 54; i++) ids.push(await commit([ids.at(-1)], `feat(editor): 改进编辑器交互 ${i + 1}\n\n完整提交说明 ${i + 1}\n`))
  const side = await commit([ids.at(-5)], 'fix(sidebar): 修复窄侧栏布局\n\n保留文件名称和修改统计。\n')
  const message = 'feat(changes): 展示 Git 提交记录\n\n添加分支关系图和可展开的提交消息。\n\n- 支持分页与状态恢复\n- 保留完整消息和父提交\n\n<img src=x onerror=alert(1)>\n'
  const merge = await commit([ids.at(-1), side], message, ['-c', 'author.name=作者甲', '-c', 'author.email=author@example.invalid', '-c', 'committer.name=提交者乙', '-c', 'committer.email=committer@example.invalid'])
  await git(workspace, ['update-ref', branch, merge]); await git(workspace, ['update-ref', 'refs/heads/fix/sidebar', side])
  await git(workspace, ['update-ref', 'refs/remotes/origin/main', ids.at(-1)])
  await git(workspace, ['tag', '-a', 'v0.2.0', '-m', '版本标签', merge])
  await chooseSource('提交记录')
  await page.locator('.dshHistory__row').first().waitFor()
  assert.equal(await page.locator('.dshHistory__row').count(), 50)
  const first = page.getByRole('button', { name: '提交：feat(changes): 展示 Git 提交记录', exact: true })
  const tooltip = page.getByRole('tooltip').filter({ hasText: `提交：${merge}` })
  await first.hover(); await tooltip.waitFor()
  const info = await tooltip.innerText()
  assert.ok(info.includes(`提交：${merge}\n作者：作者甲 <author@example.invalid>\n提交者：提交者乙 <committer@example.invalid>\n提交时间：`), info)
  assert.equal(info.split('\n').length, 4)
  assert.equal(await page.locator('.dshHistory__message').count(), 0, 'metadata is available before expansion')
  await page.mouse.move(0, 0); await page.keyboard.press('Tab'); await first.focus(); await tooltip.waitFor()
  assert.equal(await tooltip.innerText(), info, 'keyboard focus exposes the same metadata')
  await first.click(); await page.locator('.dshHistory__message').waitFor()
  assert.equal(await page.locator('.dshHistory__message').textContent(), message)
  assert.equal(await page.locator('.dshHistory__message img').count(), 0)
  assert.equal(await page.locator('.dshHistory__detail dl, .dshHistory__parent').count(), 0)
  assert.equal(await page.getByRole('button', { name: '复制提交哈希', exact: true }).count(), 0)
  assert.equal(await page.locator('.dshHistory__detail').textContent(), message)
  const sample = async () => first.evaluate(button => new Promise(resolve => {
    const panel = button.closest('.dshHistory__commit').querySelector('.dshHistory__expanded'), frames = [], start = performance.now()
    button.click()
    const frame = () => {
      frames.push(panel.getBoundingClientRect().height)
      if (performance.now() - start < 800) requestAnimationFrame(frame)
      else resolve(frames)
    }
    requestAnimationFrame(frame)
  }))
  await page.evaluate(() => {
    document.documentElement.setAttribute('data-dsh-ui', 'desktop')
    document.documentElement.setAttribute('data-dsh-desktop-animation', 'on')
  })
  const closing = await sample()
  assert.equal(closing.at(-1), 0)
  assert.ok(closing.some(height => height > 0 && height < closing[0]), 'closing retains and smoothly clips the card')
  let delayedRequests = 0
  const delayedDetails = async route => { delayedRequests++; await new Promise(resolve => setTimeout(resolve, 300)); await route.continue() }
  await page.route('**/api/desktopChanges/getCommitDetails*', delayedDetails)
  const opening = await sample()
  await page.unroute('**/api/desktopChanges/getCommitDetails*', delayedDetails)
  assert.ok(delayedRequests > 0, 'exercise a genuinely delayed detail response')
  assert.ok(opening.some(height => height > 0 && height < opening.at(-1)), 'loading and full message grow within the same surface')
  assert.equal(await page.locator('[data-dsh-ghost] .dshHistory__message, .dshHistory__detail[data-dsh-ghost]').count(), 0)
  const card = await page.locator('.dshHistory__detail').evaluate(node => ({ border: getComputedStyle(node).borderTopWidth, radius: getComputedStyle(node).borderRadius, transform: getComputedStyle(node).transform }))
  assert.equal(card.border, '1px'); assert.equal(card.radius, '8px'); assert.equal(card.transform, 'none')
  await first.evaluate(button => new Promise(resolve => {
    button.click(); setTimeout(() => { button.click(); setTimeout(resolve, 350) }, 35)
  }))
  assert.equal(await first.getAttribute('aria-expanded'), 'true')
  const settled = await page.locator('.dshHistory__expanded').first().evaluate(node => ({ height: node.getBoundingClientRect().height, content: node.firstElementChild.getBoundingClientRect().height }))
  assert.ok(Math.abs(settled.height - settled.content) < 1, 'rapid reversal settles at the full content height')
  await first.evaluate(button => { button.click(); document.documentElement.setAttribute('data-dsh-desktop-animation', 'off') })
  await page.waitForFunction(() => document.querySelector('.dshHistory__expanded').getBoundingClientRect().height === 0)
  await first.click(); await page.locator('.dshHistory__message').waitFor()
  report.checks.push('commit message card: smooth open/close and delayed content resize, no ghost duplication, animation switch stops motion')
  await first.click()
  await page.locator('.dshHistory__list').evaluate(node => { node.scrollTop = node.scrollHeight })
  await page.waitForFunction(() => document.querySelectorAll('.dshHistory__row').length === 57)
  assert.equal(await page.locator('.dshHistory__commit').evaluateAll(rows => new Set(rows.map(row => row.dataset.commitId)).size), 57)
  await page.locator('.dshHistory__list').evaluate(node => { node.scrollTop = 0 })
  await first.click(); await page.locator('.dshHistory__message').waitFor()
  await chooseSource('暂存区')
  await page.locator('.dshChanges__detail').waitFor()
  assert.equal(await page.locator('.dshChanges__file[aria-expanded=true]').count(), 1)
  await chooseSource('提交记录')
  await page.locator('.dshHistory__message').waitFor()
  assert.equal(await page.locator('.dshHistory__row').count(), 57)
  report.checks.push('history merge graph, safe complete messages, hover and keyboard metadata tooltip, 50-row paging and independent view state')
  await writeFile(join(root, 'expire-history'), '')
  await page.evaluate(async sessionId => {
    const result = await window.__CHANGES_SMOKE__.remote.desktopChanges.listCommits(sessionId, '', 0, new AbortController().signal)
    if (!result.ok) throw result.error
  }, sessionId)
  const oldest = page.locator('.dshHistory__commit').last()
  await oldest.locator('.dshHistory__row').click()
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await oldest.locator('.dshHistory__message').waitFor()
  assert.ok((await oldest.locator('.dshHistory__message').textContent()).length > 0)
  assert.equal(await page.locator('.dshHistory__row').count(), 57)
  await oldest.locator('.dshHistory__row').click()
  await page.locator('.dshHistory__list').evaluate(node => { node.scrollTop = 0 })
  report.checks.push('expired history cache automatically restores saved pages and older commit details')
  for (const dark of [false, true]) for (const width of [240, 320, 480, 720]) {
    await page.locator('.dshHistory').evaluate((panel, { dark, width }) => {
      document.body.toggleAttribute('data-ds-dark-theme', dark)
      Object.assign(panel.style, { width: width + 'px', height: '650px', position: 'fixed', top: '50px', left: '10px', background: 'var(--dsw-alias-bg-base)', zIndex: '9999' })
    }, { dark, width })
    const layout = await page.locator('.dshHistory').evaluate(panel => {
      const row = panel.querySelector('.dshHistory__commit'), svg = row.querySelector('svg')
      return { width: panel.clientWidth, scrollWidth: panel.scrollWidth, rowHeight: row.getBoundingClientRect().height, graphHeight: svg.getBoundingClientRect().height }
    })
    assert.ok(layout.scrollWidth <= layout.width + 1); assert.ok(Math.abs(layout.rowHeight - layout.graphHeight) < 1)
    if (width === 480) {
      await page.mouse.move(0, 0); await first.evaluate(node => node.blur())
      await page.locator('.dshHistory').screenshot({ path: join(root, `history-${dark ? 'dark' : 'light'}.png`) })
      await first.hover(); await tooltip.waitFor()
      await page.locator('.dshHistory').screenshot({ path: join(root, `history-tooltip-${dark ? 'dark' : 'light'}.png`) })
      await page.mouse.move(0, 0)
    }
  }
  await page.locator('.dshHistory').evaluate(panel => panel.removeAttribute('style'))
  const snapshot = await page.evaluate(() => window.__CHANGES_ADAPTER__.capture({ signal: new AbortController().signal, frontendVersion: '0.2.0-rc.2', providers: window.__CHANGES_PROVIDERS__ }))
  await page.reload(); await page.waitForFunction(() => Boolean(window.__CHANGES_SMOKE__))
  const skip = page.getByRole('button', { name: '稍后配置', exact: true }); await skip.waitFor(); await skip.click()
  const { readFile } = await import('node:fs/promises')
  await page.addScriptTag({ content: await readFile('dsh-plugin/ui-state/adapter.js', 'utf8') })
  await page.evaluate(() => { window.__CHANGES_ADAPTER__ = window.__DSH_CREATE_UI_ADAPTER__(window.__CHANGES_SMOKE__) })
  await page.evaluate(snapshot => window.__CHANGES_ADAPTER__.restore({ payload: snapshot }, { signal: new AbortController().signal, frontendVersion: '0.2.0-rc.2', providers: window.__CHANGES_PROVIDERS__ }), snapshot)
  await page.locator('.dshHistory__message').waitFor()
  assert.equal(await page.locator('.dshHistory__row').count(), 57)
  const newest = await commit([merge], 'fix(history): 自动更新提交历史\n')
  await git(workspace, ['update-ref', branch, newest])
  await page.getByRole('button', { name: '提交：fix(history): 自动更新提交历史', exact: true }).waitFor({ timeout: 15000 })
  assert.equal(await page.locator('.dshHistory__message').textContent(), message)
  report.checks.push('history light/dark narrow layout, expanded graph continuity, document restore and automatic branch updates')
  await chooseSource('暂存区')
  await page.locator('.dshChanges__detail').waitFor()
}

  const rpc = async (method, ...args) => page.evaluate(async ({ method, args }) => {
    const result = await window.__EDITOR_SMOKE__.remote.desktopFileEditor[method](...args, new AbortController().signal)
    return result.ok ? { ok: true, value: result.value } : { ok: false, code: result.error.code }
  }, { method, args })
  assert.equal((await rpc('read', sessionId, 'broken.txt')).ok, false)
  assert.equal((await rpc('read', sessionId, '..\\patch.yml')).ok, false)
  assert.equal((await rpc('read', 'not-a-session', 'notes.txt')).ok, false)
  await writeFile(join(workspace, 'large.txt'), 'a'.repeat(2 * 1024 * 1024 + 1))
  assert.equal((await rpc('read', sessionId, 'large.txt')).ok, false)

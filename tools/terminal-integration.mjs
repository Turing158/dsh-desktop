/** Real Windows/WebView2 acceptance runner. Requires an isolated debug host. */
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { connect } from './terminal-cdp.mjs'
const cdp = await connect(Number(process.env.CDP_PORT || 9341))
const sleep = ms => new Promise(r => setTimeout(r, ms))
const report = { checks: [] }
const check = (name, value) => { assert.ok(value, name); report.checks.push(name) }
async function until(expression, timeout = 12000) {
  const end = Date.now() + timeout
  while (Date.now() < end) { const value = await cdp.evaluate(expression); if (value) return value; await sleep(100) }
  throw Error('Timed out: ' + expression)
}
try {
  await until('Boolean(window.__DSH_UI_BOOT__?.smoke && window.__DSH_TERMINAL_SMOKE__ && window.__DSH_TERMINAL_IDENTITY__)')
  await cdp.evaluate(`(()=>{
    const c=window.__DSH_TERMINAL_SMOKE__.ctx;
    window.T={c,invoke:(name,args={})=>window.__TAURI__.core.invoke(name,{identity:window.__DSH_TERMINAL_IDENTITY__,...args}),
      wire:s=>({terminalId:s.terminalId,runId:s.runId}),sleep:ms=>new Promise(r=>setTimeout(r,ms)),
      sid:c.sessions.list.getSnapshot().current};
    T.store=c.slots.resolveStore(c.slots.entriesOfSlot('rightbar.session')[0].store,{key:T.sid,ctx:c.sessions.scope(T.sid)});
    T.tabs=()=>Object.values(T.store.getSnapshot().bySession[T.sid]?.layout.tabs||{});
    for(const b of document.querySelectorAll('button'))if(b.textContent==='稍后配置')b.click();
    c.sidebarRight.openTab('desktop-terminal');
  })()`)
  await until(`document.querySelector('[data-dsh-terminal-status=running]')!==null`)
  check('WebView2 Channel and exact-origin profiles', (await cdp.evaluate(`T.invoke('terminal_profiles')`)).length > 0)
  check('current tab is tracked by real layout', await cdp.evaluate(`window.__DSH_TERMINAL_SMOKE__.registry.orphans().length===0`))
  const fold = `((document.querySelector('.xterm-rows')?.innerText || '').replace(/\\s+/g, ''))`
  // A running native process can precede channel replay and the first prompt.
  // Wait for the displayed shell before sending real keys into a new view.
  await until(`${fold}.includes('>')`)
  await cdp.evaluate(`for(const b of document.querySelectorAll('button'))if(b.textContent==='稍后配置')b.click()`)
  await cdp.evaluate(`document.querySelector('.xterm-helper-textarea').focus()`)
  await sleep(400)
  // The emoji is GENERATED by the shell, never typed: ConPTY on this Windows build
  // drops astral-plane characters from its INPUT pipe itself — raw UTF-8 written
  // straight to the PTY loses them too. Platform limit, recorded in the README;
  // the OUTPUT path carries the emoji fine. ASCII rides in through real
  // per-character key events, so nothing duplicates; the Chinese chunk uses
  // insertText, the closest CDP emulation of an IME commit, whose delivery may
  // repeat the payload — each assertion matches a substring that survives that.
  const typeAscii = async text => {
    for (const ch of text) {
      await cdp.send('Input.dispatchKeyEvent', { type: 'keyDown', key: ch, text: ch, unmodifiedText: ch, windowsVirtualKeyCode: 0 })
      await cdp.send('Input.dispatchKeyEvent', { type: 'keyUp', key: ch, windowsVirtualKeyCode: 0 })
    }
  }
  const pressEnter = async () => {
    await cdp.send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Enter', code: 'Enter', text: '\r', unmodifiedText: '\r', windowsVirtualKeyCode: 13 })
    await cdp.send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13 })
  }
  await typeAscii('[char]::ConvertFromUtf32(0x1F600)')
  await pressEnter()
  await until(`${fold}.includes('😀')`)
  check('real keyboard input and Unicode output', true)
  await cdp.send('Input.insertText', { text: 'echo 中文回显' })
  await pressEnter()
  await until(`${fold}.includes('中文回显')`)
  check('chinese IME-style input round-trips', true)
  const primary = await cdp.evaluate(`(async()=>{const list=await T.invoke('terminal_list');T.primary=list.find(s=>s.resourceKey===T.tabs().find(t=>t.kind==='desktop-terminal').contentId);return T.primary})()`)
  await cdp.evaluate(`T.store.actions.duplicateTab(T.sid,T.tabs().find(t=>t.kind==='desktop-terminal').id)`)
  await until(`T.tabs().filter(t=>t.kind==='desktop-terminal').length===2`)
  await sleep(400)
  check('duplicate shares one PTY', (await cdp.evaluate(`T.invoke('terminal_list')`)).filter(s => s.resourceKey === primary.resourceKey).length === 1)
  await cdp.evaluate(`T.c.sidebarRight.close(T.tabs().find(t=>t.kind==='desktop-terminal').id)`)
  await sleep(300)
  check('closing one duplicate keeps PTY', (await cdp.evaluate(`T.invoke('terminal_list')`)).some(s => s.terminalId === primary.terminalId))
  await cdp.evaluate(`T.c.sidebarRight.openTab('desktop-terminal')`)
  await until(`T.tabs().filter(t=>t.kind==='desktop-terminal').length===2`)
  await until(`T.invoke('terminal_list').then(s=>s.length>=2)`)
  check('new guide creates independent address and PTY', (await cdp.evaluate(`T.invoke('terminal_list')`)).length === 2)
  await cdp.evaluate(`T.c.sidebarRight.toggleExpanded()`)
  await sleep(150)
  check('hidden sidebar retains sessions', (await cdp.evaluate(`T.invoke('terminal_list')`)).length === 2)
  await cdp.evaluate(`T.c.sidebarRight.toggleExpanded()`)
  const stale = await cdp.evaluate(`(async()=>{try{await T.invoke('terminal_profiles',{identity:{...window.__DSH_TERMINAL_IDENTITY__,documentGeneration:0}});return false}catch{return true}})()`)
  check('old document identity denied', stale)
  await cdp.evaluate(`T.c.sidebarRight.close(T.tabs().find(t=>t.contentId===T.primary.resourceKey).id)`)
  await until(`T.invoke('terminal_list').then(s=>!s.some(x=>x.terminalId===T.primary.terminalId))`)
  check('last reference closes native session', true)
  const before = await cdp.evaluate(`T.invoke('terminal_list')`)
  await cdp.send('Page.reload')
  await until('Boolean(window.__DSH_TERMINAL_SMOKE__ && window.__DSH_TERMINAL_IDENTITY__)')
  const after = await cdp.evaluate(`window.__TAURI__.core.invoke('terminal_list',{identity:window.__DSH_TERMINAL_IDENTITY__})`)
  check('refresh preserves existing run identity', before[0].terminalId === after[0].terminalId && before[0].runId === after[0].runId)
  await cdp.evaluate(`window.__DSH_TERMINAL_SMOKE__.ctx.sidebarRight.openResource(${JSON.stringify(after[0].resourceKey)})`)
  await until(`(() => { const t = (document.querySelector('.xterm-rows')?.innerText || '').replace(/\\s+/g, ''); return t.includes('PS') && t.includes('>') })()`)
  check('existing stream replays after page refresh', true)
  // Cleanup uses explicit IPC in the disposable test app, even after a UI assertion fails.
} finally {
  try { await cdp.evaluate(`(async()=>{const identity=window.__DSH_TERMINAL_IDENTITY__;for(const s of await window.__TAURI__.core.invoke('terminal_list',{identity}))await window.__TAURI__.core.invoke('terminal_close',{identity,terminalId:s.terminalId,runId:s.runId});})()`) } catch {}
  cdp.close()
  const dir = resolve('src-tauri/target/terminal-live'); await mkdir(dir, { recursive:true }); await writeFile(dir+'/integration.json',JSON.stringify(report,null,2))
}
console.log(JSON.stringify(report,null,2))
